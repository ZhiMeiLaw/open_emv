/* ------------------------------------------------------------------ */
/*  Dictionary item — per-kernel tag definition                       */
/* ------------------------------------------------------------------ */
typedef struct {
    uint32_t tag;                     /* EMV tag number                      */
    tag_source_t source;              /* Where does this tag's value come from */
    tag_type_t type;                  /* Data type (numeric, binary, etc.)    */
    uint8_t min_len;                  /* Minimum byte length                 */
    uint8_t max_len;                  /* Maximum byte length                 */
    uint8_t mandatory : 1;            /* Must be present for kernel run       */
    char description[MAX_TAG_DESCRIPTION_LEN];
} dict_item_t;

