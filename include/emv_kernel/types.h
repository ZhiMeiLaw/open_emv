/* Combine byte pairs into uint32_t tag number */
#define EMV_TAG(b1)            ((uint32_t)(b1))
#define EMV_TAG2(b1, b2)       (((uint32_t)(b1) << 8) | (uint32_t)(b2))
#define EMV_TAG3(b1, b2, b3)   (((uint32_t)(b1) << 16) | ((uint32_t)(b2) << 8) | (uint32_t)(b3))
#define EMV_TAG4(b1, b2, b3, b4) \
    (((uint32_t)(b1) << 24) | ((uint32_t)(b2) << 16) | ((uint32_t)(b3) << 8) | (uint32_t)(b4))

