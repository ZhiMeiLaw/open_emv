/** Pack two BCD digits into one byte (e.g. 0x9F02 amount encoding). */
static inline uint8_t bcd_encode_byte(uint8_t low, uint8_t high)
{
    return (high << 4) | (low & 0x0Fu);
}

/** Decode a BCD byte to separate tens and units. */
static inline void bcd_decode_byte(uint8_t bcd, uint8_t *tens, uint8_t *units)
{
    if (tens) *tens = (bcd >> 4) & 0x0Fu;
    if (units) *units = bcd & 0x0Fu;
}

/** Convert 2-byte BCD amount field to uint32_t. */
static inline uint32_t bcd_2byte_to_uint(const uint8_t *bcd_buf)
{
    return (uint32_t)bcd_buf[0] * 256u + bcd_buf[1];
}

/** Store a uint32_t as 2-byte BCD. Caller must ensure buf has room for 2 bytes. */
static inline void uint_to_bcd_2byte(uint32_t val, uint8_t *out)
{
    out[0] = bcd_encode_byte((uint8_t)(val % 10), (uint8_t)((val / 10) % 10));
    out[1] = bcd_encode_byte((uint8_t)((val / 100) % 10), (uint8_t)((val / 1000) % 10));
}

/** Convert 6-byte BCD (EMV payment amount format) to uint32_t. */
static inline uint32_t bcd_6byte_to_uint(const uint8_t *bcd_buf)
{
    uint32_t val = 0;
    for (int i = 0; i < 6; i++) {
        val = val * 100u + (uint32_t)bcd_buf[i];
    }
    return val;
}

/** Store a uint32_t as 6-byte BCD (EMV payment amount format). */
static inline void uint_to_bcd_6byte(uint32_t val, uint8_t *out)
{
    for (int i = 5; i >= 0; i--) {
        out[i] = bcd_encode_byte((uint8_t)(val % 10), (uint8_t)((val / 10) % 10));
        val /= 100;
    }
}

/** Convert 2-byte big-endian integer to host order. */
static inline uint16_t be16_to_host(const uint8_t *buf)
{
    return ((uint16_t)buf[0] << 8) | (uint16_t)buf[1];
}

/** Store a 16-bit host-order integer as big-endian bytes. */
static inline void host_to_be16(uint16_t val, uint8_t *buf)
{
    buf[0] = (uint8_t)(val >> 8);
    buf[1] = (uint8_t)val;
}

/** Convert 4-byte big-endian integer to host order. */
static inline uint32_t be32_to_host(const uint8_t *buf)
{
    return ((uint32_t)buf[0] << 24) | ((uint32_t)buf[1] << 16) |
           ((uint32_t)buf[2] << 8)  | (uint32_t)buf[3];
}

/** Store a 32-bit host-order integer as big-endian bytes. */
static inline void host_to_be32(uint32_t val, uint8_t *buf)
{
    buf[0] = (uint8_t)(val >> 24);
    buf[1] = (uint8_t)(val >> 16);
    buf[2] = (uint8_t)(val >> 8);
    buf[3] = (uint8_t)val;
}

